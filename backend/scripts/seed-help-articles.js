async function seedHelpArticles() {
  try {
    logger.info('开始初始化帮助文档数据...')

    // 测试数据库连接
    await sequelize.authenticate()
    logger.info('数据库连接成功')

    // 同步模型（添加新字段）
    logger.info('同步数据库模型...')
    await sequelize.sync({ alter: true })
    logger.info('数据库模型同步完成')

    // 只查询帮助文档类型的数据
    const existingCount = await Announcement.count({
      where: { type: 'help' }
    })
    
    if (existingCount > 0) {
      logger.info(`数据库中已有 ${existingCount} 条帮助文档，跳过初始化`)
      process.exit(0)
    }

    // 批量创建帮助文档
    for (const article of helpArticles) {
      await Announcement.create(article)
      logger.info(`创建帮助文档: [${article.category}] ${article.title}`)
    }

    logger.info(`成功创建 ${helpArticles.length} 条帮助文档`)
    process.exit(0)
  } catch (error) {
    logger.error('初始化帮助文档失败:', error)
    process.exit(1)
  }
}

// 执行初始化
seedHelpArticles()
